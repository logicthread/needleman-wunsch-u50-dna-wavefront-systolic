/* kernel_driver.cpp -- runs the ACTUAL kernel source (src/kernel_tile_1b_s1t.cpp, top nw_tile_u50) on a file of
 * cases and prints raw outputs in the same format as dut_driver.cpp, so check_cases.py judges both alike.
 *
 * This is "csim on a laptop": the kernel is compiled as plain C++ against the stand-in headers in hls_stub/
 * (see docs/VERIFICATION.md, "what the stand-ins are and are not"). The memory layout, descriptor and
 * decode of the direction beats follow test/tile_1b_tb_s1t.cpp (the Vitis csim testbench).
 *
 * Per case it reports: kernel score (mem[S_OFF]), on-card walker results (status, nops, score, fills, ops),
 * the host walker run over the beats THE KERNEL WROTE, the path re-scored from the kernel's decoded direction
 * matrix, and the decoded direction matrix itself (cells <= DIRS_MAX) for comparison with an independent DP.
 * Cases whose direction stream would not fit WV_DIRDEPTH, or longer than WV_QDEPTH/WV_RDEPTH, print SKIP.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <string>
#include <vector>
#include <ap_int.h>

#ifndef NW_PE
#error "define NW_PE"
#endif
#ifndef WV_TILE_PE
#define WV_TILE_PE 128
#endif
#define WV_TILES     (NW_PE / WV_TILE_PE)
#define WV_NCH       WV_TILES
#define WV_DIR_PORTS WV_NCH
#define WV_PER_WORD  32
#define WV_DIR_SCYC  5
#define WV_DIR_SBEATS 2
#define WV_NMIN      (NW_PE + 8 * WV_TILE_PE)
#define WV_BWIN      640
#define WV_DIR_GROUP 5
#define WV_TBD_EN     (WV_DIR_PORTS + 0)
#define WV_TBD_OPS    (WV_DIR_PORTS + 1)
#define WV_TBD_CAP    (WV_DIR_PORTS + 2)
#define WV_TBD_NOPS   (WV_DIR_PORTS + 3)
#define WV_TBD_SCORE  (WV_DIR_PORTS + 4)
#define WV_TBD_STATUS (WV_DIR_PORTS + 5)
#define WV_TBD_FILLS  (WV_DIR_PORTS + 6)
#ifndef WV_QDEPTH
#define WV_QDEPTH 256
#endif
#ifndef WV_RDEPTH
#define WV_RDEPTH 256
#endif
#ifndef WV_BDEPTH
#define WV_BDEPTH 8192
#endif
#ifndef WV_DIRDEPTH
#define WV_DIRDEPTH 4096
#endif
#define DIRS_MAX 60000
#define NOTRUN (-1000000000000LL)
typedef ap_uint<512> dirbeat;

extern "C" {
#include "nw_wave.h"
#include "nw.h"
#include "nw_host_traceback.h"
}
#include "kernel_proto.inc"   /* generated by build_kernel.sh: nw_tile_u50 prototype + WV_DIRARGS for WV_DIR_PORTS ports */
extern int wv_qstarve;

static std::vector<uint64_t> mem;
static int64_t Q_OFF, R_OFF, B_OFF, S_OFF, OPS_OFF, OPS_CAP;
static std::vector<dirbeat> dbuf[WV_DIR_PORTS];

struct fetch_ctx { };
static int fetch(void *, int port, int64_t first, int64_t count, uint8_t *dst) {
    for (int64_t b = 0; b < count; ++b) {
        const dirbeat &v = dbuf[port][(size_t)(first + b)];
        for (int i = 0; i < 64; ++i) dst[b * 64 + i] = (uint8_t)(unsigned)v.range(8 * i + 7, 8 * i);
    }
    return 0;
}
static uint8_t code(char c) { switch (c) { case 'A': return 0; case 'C': return 1; case 'G': return 2; case 'T': return 3; default: return 4; } }

static void run_case(const char *id, const char *cls, const std::string &qs, const std::string &rs) {
    const int64_t m = (int64_t)qs.size(), n = (int64_t)rs.size();
    if (cls[0] == 'N' || cls[0] == 'Z' || m == 0 || n == 0) { printf("SKIP %s model-only class\n", id); return; }
    std::vector<uint8_t> q(m), r(n);
    for (int64_t i = 0; i < m; ++i) q[i] = code(qs[i]);
    for (int64_t j = 0; j < n; ++j) r[j] = code(rs[j]);
    const int64_t nbands = (m + NW_PE - 1) / NW_PE;
    const int64_t gap = (n + WV_BWIN < WV_NMIN) ? (int64_t)WV_NMIN - n : (int64_t)WV_BWIN;
    const int64_t S = n + gap;
    const int64_t clast = (nbands - 1) * S + n + WV_TILE_PE;
    const int64_t cmax = (clast + WV_DIR_SCYC - 1) / WV_DIR_SCYC * WV_DIR_SCYC;
    const int64_t ntot = (cmax / WV_DIR_SCYC) * WV_DIR_SBEATS;
    if (ntot > WV_DIRDEPTH) { printf("SKIP %s dir depth (%lld beats > %d)\n", id, (long long)ntot, WV_DIRDEPTH); return; }
    if (m > (int64_t)WV_QDEPTH * WV_PER_WORD || n > (int64_t)WV_RDEPTH * WV_PER_WORD) { printf("SKIP %s exceeds QDEPTH/RDEPTH\n", id); return; }
    if (m + n + 8 > OPS_CAP) { printf("SKIP %s ops area\n", id); return; }

    std::fill(mem.begin(), mem.end(), 0ull);
    for (int64_t i = 0; i < m; ++i) mem[Q_OFF + i / WV_PER_WORD] |= (uint64_t)(q[i] & 3) << (2 * (i % WV_PER_WORD));
    for (int64_t j = 0; j < n; ++j) mem[R_OFF + j / WV_PER_WORD] |= (uint64_t)(r[j] & 3) << (2 * (j % WV_PER_WORD));
    for (int p = 0; p < WV_DIR_PORTS; ++p) std::fill(dbuf[p].begin(), dbuf[p].end(), 0);
    mem[S_OFF] = 0;
    for (int p = 0; p < WV_DIR_PORTS; ++p) mem[B_OFF + p] = (uint64_t)((const uint64_t *)dbuf[p].data() - mem.data());
    mem[B_OFF + WV_TBD_EN] = 1; mem[B_OFF + WV_TBD_OPS] = OPS_OFF; mem[B_OFF + WV_TBD_CAP] = OPS_CAP;

    const int starve0 = wv_qstarve;
    nw_tile_u50(mem.data(), Q_OFF, R_OFF, B_OFF, S_OFF, m, n, WV_DIRARGS);

    const int64_t gold = nw_align_ref(q.data(), (int32_t)m, r.data(), (int32_t)n);
    const int64_t kscore = (int64_t)mem[S_OFF];
    /* decode the kernel's direction beats (same inverse mapping as the Vitis testbench) */
    static const unsigned P3[5] = {81, 27, 9, 3, 1};
    std::vector<uint8_t> dirs((size_t)m * n, 0xff);
    int64_t b3bad = 0;
    for (int64_t row = 0; row < m; ++row) {
        const int64_t band = row / NW_PE, rib = row % NW_PE;
        const int k = (int)(rib / WV_TILE_PE), il = (int)(rib % WV_TILE_PE);
        for (int64_t j = 0; j < n; ++j) {
            const int64_t c = band * S + j + il;
            const int64_t beat = (c / 5) * 2 + il / 64;
            const unsigned byte = (unsigned)dbuf[k][(size_t)beat].range(8 * (il % 64) + 7, 8 * (il % 64));
            if (byte > 242u) { ++b3bad; dirs[(size_t)row * n + j] = 0xff; }
            else dirs[(size_t)row * n + j] = (uint8_t)((byte / P3[c % 5]) % 3u);
        }
    }
    bool unwritten = b3bad != 0;
    for (auto d : dirs) if (d == 0xff) { unwritten = true; break; }
    int64_t dpath = NOTRUN, nk = 0;
    if (!unwritten) dpath = nw_wave_traceback(q.data(), m, r.data(), n, dirs.data(), &nk);
    /* host walker over the beats the kernel wrote */
    nwh_geom g = { m, n, NW_PE, WV_TILE_PE, 2, -1, -2 };
    std::vector<uint8_t> hops((size_t)(m + n + 8)); int64_t hscore = NOTRUN;
    int64_t hn = nw_host_traceback(&g, q.data(), r.data(), fetch, nullptr, hops.data(), (int64_t)hops.size(), &hscore, 0, 0);
    const int64_t cnops = (int64_t)mem[B_OFF + WV_TBD_NOPS], csc = (int64_t)mem[B_OFF + WV_TBD_SCORE];
    int64_t cst = (int64_t)mem[B_OFF + WV_TBD_STATUS];
    const int64_t cfill = (int64_t)mem[B_OFF + WV_TBD_FILLS];
    int64_t diff = -1;
    if (cnops == hn)
        for (int64_t s = 0; s < cnops; ++s)
            if (((mem[OPS_OFF + s / 32] >> (2 * (s % 32))) & 3) != hops[s]) { diff = s; break; }
    if (wv_qstarve != starve0) cst = -100 - (wv_qstarve - starve0);   /* query starvation shows up as a bad status */
    if (b3bad) cst = -200;                                           /* impossible base-3 byte in the kernel's beats */
    std::string ops_s; ops_s.reserve((size_t)cnops);
    for (int64_t s = 0; s < cnops; ++s) ops_s.push_back((char)('0' + ((mem[OPS_OFF + s / 32] >> (2 * (s % 32))) & 3)));
    printf("CASE %s %s %lld %lld %lld %lld %lld %lld %lld %lld %lld %lld %lld %lld\n", id, cls, (long long)m, (long long)n,
           (long long)gold, (long long)kscore, (long long)dpath, (long long)hscore, (long long)hn, (long long)cst,
           (long long)cnops, (long long)csc, (long long)cfill, (long long)diff);
    if (!ops_s.empty()) printf("OPS %s\n", ops_s.c_str());
    if (!unwritten && m * n <= DIRS_MAX) { std::string d; for (auto x : dirs) d.push_back((char)('0' + x)); printf("DIRS %s\n", d.c_str()); }
    fflush(stdout);
}

int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: %s cases.txt\n", argv[0]); return 2; }
    FILE *f = fopen(argv[1], "r"); if (!f) { perror(argv[1]); return 2; }
    Q_OFF = 0; R_OFF = Q_OFF + WV_QDEPTH; B_OFF = R_OFF + WV_RDEPTH; S_OFF = B_OFF + (WV_BDEPTH + 7) / 8;
    OPS_OFF = S_OFF + 1; OPS_CAP = (int64_t)(WV_QDEPTH + WV_RDEPTH) * WV_PER_WORD;
    mem.assign((size_t)(OPS_OFF + OPS_CAP / 32 + 1), 0ull);
    for (int p = 0; p < WV_DIR_PORTS; ++p) dbuf[p].assign(WV_DIRDEPTH, 0);
    printf("DRIVER KERNEL NW_PE=%d tiles=%d NMIN=%d QDEPTH=%d RDEPTH=%d DIRDEPTH=%d\n", NW_PE, WV_TILES, WV_NMIN, WV_QDEPTH, WV_RDEPTH, WV_DIRDEPTH);
    static char *line = nullptr; size_t cap = 0; ssize_t len;
    while ((len = getline(&line, &cap, f)) > 0) {
        char id[64], cls[64]; long long m, n; int off = 0;
        if (line[0] == '#' || sscanf(line, "%63s %63s %lld %lld %n", id, cls, &m, &n, &off) < 4) continue;
        std::string q, r; const char *p = line + off; const char *sp = strchr(p, ' '); if (!sp) continue;
        q.assign(p, sp - p); r.assign(sp + 1, strcspn(sp + 1, "\r\n"));
        if (q == "-") q.clear(); if (r == "-") r.clear();
        run_case(id, cls, q, r);
    }
    printf("END\n");
    fflush(stdout);
    _exit(0);   /* task threads are detached and blocked on empty streams: do not run static destructors */
}
